"""Alternate hypotheses — why a person may NOT have been involved.

For each line of inquiry ("X may have been involved in the incident recorded in <case>"), KRONOS builds the competing
innocent explanations and tests them against the same records:

  A1 Was elsewhere at the time (alibi)               A5 The contact was routine, not coordination
  A2 Was near the scene for a routine reason          A6 Named, or given a role, in error
  A3 Someone else used the phone / handset            A7 Mistaken identity (namesake, wrong match)
  A4 The money has a legitimate explanation           A8 The location records are unreliable

An alternate is shown as *supported* only when records support it (each item cites its evidence IDs); otherwise it is
listed as "considered — no supporting record", never invented. Each alternate states which supporting evidence of the
line of inquiry it would explain away, and the test that would tell the two apart (Analysis of Competing Hypotheses:
the evidence that discriminates matters, not the evidence that fits everything). The presumption of innocence is the
default; nothing here is a finding or a probability of guilt.
"""
from __future__ import annotations

import math
import re
from collections import defaultdict

import pandas as pd

from ... import db
from ..identity import resolver
from ..store import events
from ..temporal import travel

REL = {"HIGH": 1.0, "MEDIUM": 0.8, "LOW": 0.55}
LEGIT = re.compile(r"salary|rent|fee|loan|emi|property|sale deed|registered|invoice|business|supplier|purchase|gift|"
                   r"wedding|medical|school|refund|insurance|tax|bill|consultancy", re.I)
SPEC = {
    "A1": ("Was elsewhere at the time (alibi)", "{n} was somewhere else when the incident happened.", 0.95, ["LOCATION", "FIR"],
           "Verify the alibi record independently (CCTV, witnesses or receipts at that place and time) and check whether the "
           "device could have been carried by someone else."),
    "A2": ("Was near the scene for a routine reason", "{n} was near the scene because they regularly go there (home, work, market), "
           "not because of the incident.", 0.55, ["LOCATION"],
           "Establish why the person is regularly there (address, employment, shop) and compare the incident-time visit with "
           "their usual pattern (time of day, duration)."),
    "A3": ("Someone else used the phone or handset", "Some records attributed to {n} were generated by another person using the same "
           "phone or handset.", 0.6, ["COMMUNICATION", "LOCATION"],
           "Handset forensics and SIM CAF/KYC; establish who carried the handset at the incident time (the other user's location, CCTV)."),
    "A4": ("The money has a legitimate explanation", "The flagged money movements of {n} have an ordinary purpose (salary, rent, "
           "property, business) or belong to a co-holder of the account.", 0.45, ["FINANCIAL"],
           "Obtain full statements, invoices or agreements and KYC; confirm the stated purpose with the counter-party."),
    "A5": ("The contact was routine, not coordination", "{n}'s calls and messages reflect a long-standing relationship (family, work, "
           "business), not planning of the incident.", 0.4, ["COMMUNICATION"],
           "Examine message content and the timing of contact relative to the incident; establish the relationship."),
    "A6": ("Named or given a role in error", "{n} was named in the FIR, or assigned a role, without an independent basis.",
           0.5, ["FIR"],
           "Re-examine the FIR and statements; record the person's statement and the informant's basis for naming them."),
    "A7": ("Mistaken identity", "Records belonging to someone else (a namesake or a wrongly matched profile) were attributed to {n}.",
           0.45, ["IDENTITY", "FIR"],
           "Confirm identity with photograph or fingerprints (NAFIS), father's name and address from the FIR particulars."),
    "A8": ("The location records are unreliable", "{n}'s location records are imprecise or inconsistent (tower-level accuracy, "
           "cloned or shared SIM), so they do not reliably place them at the scene.", 0.5, ["LOCATION"],
           "Request a tower dump and the handset's GPS logs; check for SIM cloning; rely on high-accuracy fixes only."),
}


def _strength(items: list[dict], base: float) -> float:
    """Diminishing returns: 1st item full weight, then ×0.5, ×0.25 …; mapped to 0–1 with 1 − e^(−x)."""
    tot = 0.0
    for k, it in enumerate(sorted(items, key=lambda x: -REL.get(x.get("reliability", "MEDIUM"), 0.8))):
        w = base * REL.get(it.get("reliability", "MEDIUM"), 0.8) * it.get("factor", 1.0) * 0.5 ** k
        it["weight"] = round(w, 3)
        tot += w
    return round(1 - math.exp(-1.6 * tot), 3)


def _place(v) -> str:
    return v if isinstance(v, str) and v.strip() and v.lower() != "nan" else "an unnamed place"


def _label(s: float) -> str:
    return "Strong" if s >= 0.6 else "Moderate" if s >= 0.35 else "Weak" if s > 0 else "Not supported"


def build(case_id: str, pid: str, a: dict, I: dict) -> dict:
    """a = hypothesis.assess_person(...) for this person; I = case_intel.get(case_id)."""
    df = events()
    name = a["name"]
    ov = I["overview"]
    inc_ts = pd.Timestamp(ov["incident_ts"]) if ov.get("incident_ts") else None
    lat, lon = ov.get("incident_lat"), ov.get("incident_lon")
    ev = defaultdict(list)

    # A1 alibi — records placing the person far away near the incident time
    for x in I["location"]["namedPersonsElsewhere"]:
        if x["personId"] != pid:
            continue
        m = abs(x["minutesFromIncident"])
        ev["A1"].append({"text": f"Recorded at {_place(x['location'])}, {x['distanceKm']} km from the scene, {m} min "
                                 f"{'before' if x['minutesFromIncident'] < 0 else 'after'} the incident"
                                 + (" — could not have reached the scene by road in that time" if not x.get("reachableByRoad")
                                    else " — the scene was reachable by road in that time, so this is only a partial alibi"),
                         "evidenceIds": [x["evidenceId"]], "reliability": x.get("reliability") or "MEDIUM",
                         "factor": (1.0 if m <= 60 else 0.7) * (1.0 if not x.get("reachableByRoad") else 0.3)})

    # A2 routine presence — the person was often at the incident place on other days
    pe = df[(df.person_id == pid) & df.latitude.notna() & df.ts.notna()]
    near_now = [x for x in I["location"]["nearIncident"] if x["personId"] == pid]
    if inc_ts is not None and lat is not None and len(pe):
        d = pe.apply(lambda r: travel.haversine_km(lat, lon, r.latitude, r.longitude), axis=1)
        other_days = pe[(d <= 1.0) & ((pe.ts - inc_ts).abs() > pd.Timedelta(days=1))]
        days = other_days.ts.dt.date.nunique()
        if days >= 3:
            ev["A2"].append({"text": f"Recorded within 1 km of the scene on {days} other days "
                                     f"({other_days.ts.min():%d %b} – {other_days.ts.max():%d %b}), so presence there is part of their routine",
                             "evidenceIds": list(other_days.sort_values("ts").evidence_id.iloc[[0, len(other_days) // 2, -1]].unique()),
                             "reliability": "HIGH", "factor": min(1.0, days / 8)})

    # A3 another user of the handset / phone
    for c in a["contradicting"]:
        if c["source"] == "DEVICE":
            ev["A3"].append({"text": c["text"], "evidenceIds": c["evidenceIds"], "reliability": c.get("reliability", "HIGH")})
    for c in resolver.list_candidates(person_id=pid):
        if c["band"] == "INSUFFICIENT_EVIDENCE" and any("shared device" in r for r in c["reasons"]):
            other = c["personB"] if c["personA"] == pid else c["personA"]
            ev["A3"].append({"text": f"Shares a handset with {other} but is a different person (household or shared device)",
                             "evidenceIds": [c["candidateId"]], "reliability": "MEDIUM", "factor": 0.8})

    # A4 legitimate money — stated purposes / recorded alternative explanations / shared accounts
    mine = [f for f in I["financial"]["flagged"] if pid in (f["sender"], f["receiver"])]
    top_amt = max([f["amount"] for f in mine] or [1])
    for f in sorted(mine, key=lambda f: -f["amount"]):
        alt = f.get("alternativeExplanation")
        if alt or LEGIT.search(f.get("purpose") or ""):
            ev["A4"].append({"text": f"Flagged {f['channel']} ₹{f['amount']:,.0f} on {f['timestamp']} has a stated purpose '{f['purpose']}'"
                                     + (f" — {alt}" if alt else ""), "evidenceIds": [f["evidenceId"]], "reliability": "MEDIUM",
                             "factor": max(0.15, f["amount"] / top_amt)})      # small payments explain little
    for c in a["contradicting"]:
        if c["source"] == "FINANCIAL":
            ev["A4"].append({"text": c["text"], "evidenceIds": c["evidenceIds"], "reliability": c.get("reliability", "MEDIUM"), "factor": 0.8})
    ev["A4"] = ev["A4"][:4]

    # A5 routine contact — the relationship predates the incident by weeks
    if inc_ts is not None:
        for p in I["communication"]["pairs"]:
            if pid not in p["persons"] or not p.get("first"):
                continue
            lead = (inc_ts - pd.Timestamp(p["first"])).days
            if lead >= 21:
                other = p["names"][1 - p["persons"].index(pid)]
                ev["A5"].append({"text": f"In contact with {other} since {p['first'][:10]}, {lead} days before the incident "
                                         f"({p['calls']} calls, {p['messages']} messages) — a long-standing relationship",
                                 "evidenceIds": p["evidenceIds"][:2], "reliability": "HIGH", "factor": min(1.0, lead / 60)})
        ev["A5"] = sorted(ev["A5"], key=lambda x: -x["factor"])[:3]
        ai = I["communication"].get("aroundIncident") or {}
        if ev["A5"] and ai and ai.get("expectedFromBaseline") and ai.get("count", 0) <= 1.3 * ai["expectedFromBaseline"]:
            ev["A5"].append({"text": f"Contact around the incident ({ai['count']}) is close to the normal baseline "
                                     f"(≈{ai['expectedFromBaseline']}), with no unusual spike", "evidenceIds": ai.get("namedPersonEvidence", [])[:2],
                             "reliability": "MEDIUM", "factor": 0.7})

    # A6 named in error — FIR wording, machine-extracted role, only the FIR links them
    person = a.get("person") or {}
    for c in a["contradicting"]:
        if c["source"] == "FIR" or c["source"] == "ANALYSIS":
            ev["A6"].append({"text": c["text"], "evidenceIds": c["evidenceIds"], "reliability": c.get("reliability", "MEDIUM")})
    roles = person.get("roles") or []
    if roles and roles[0]["method"] == "FIR_NER" and roles[0]["role"] in ("PRINCIPAL_ACCUSED", "ACCUSED", "ASSOCIATE"):
        ev["A6"].append({"text": "The accused role was extracted from the FIR text by the NER engine, not recorded in the FIR's "
                                 "structured accused field", "evidenceIds": person.get("evidenceIds", [])[:1], "reliability": "MEDIUM"})

    # A7 mistaken identity — namesakes, contradicted identity matches
    same = db.query("SELECT person_id FROM persons WHERE lower(display_name)=lower(%s) AND person_id<>%s AND "
                    "coalesce(origin,'SYNTHETIC')<>'PUBLIC_RECORD'", (name, pid))
    if same:
        ev["A7"].append({"text": f"{len(same)} other person record(s) share the name '{name}' "
                                 f"({', '.join(r['person_id'] for r in same[:3])}), so name-based records can be misattributed",
                         "evidenceIds": [], "reliability": "MEDIUM", "factor": min(1.0, 0.5 + 0.25 * len(same))})
    for c in a["contradicting"]:
        if c["source"] == "IDENTITY":
            ev["A7"].append({"text": c["text"], "evidenceIds": c["evidenceIds"], "reliability": c.get("reliability", "MEDIUM")})

    # A8 unreliable location — impossible-travel flags, tower-level accuracy near the scene
    for f in travel.detect(pid)[:3]:
        ev["A8"].append({"text": f"Location inconsistency ({f['verdict'].replace('_', ' ').lower()}): {_place(f['first']['location'])} → "
                                 f"{_place(f['second']['location'])}, {f['distanceKm']} km in {f['elapsedMinutes']} min",
                         "evidenceIds": [f["first"]["evidenceId"], f["second"]["evidenceId"]], "reliability": "HIGH",
                         "factor": 1.0 if f["verdict"] != "REQUIRES_AIR_TRAVEL" else 0.4})
    for x in near_now:
        if (x.get("accuracyM") or 0) >= 1000:
            ev["A8"].append({"text": f"The record placing them near the scene ({x['modality']}) is only accurate to about "
                                     f"{round((x['accuracyM'] or 0) / 1000, 1)} km", "evidenceIds": [x["evidenceId"]], "reliability": "HIGH"})

    # ---- assemble, with explain-away links to the supporting evidence of the line of inquiry
    support = a["supporting"]
    alts, considered = [], []
    for code, (title, statement, base, explains, test) in SPEC.items():
        items = ev.get(code) or []
        if not items:
            considered.append({"code": code, "title": title})
            continue
        s = _strength(items, base)
        exp = [i for i, x in enumerate(support) if x["source"] in explains]
        addresses = bool(exp) or code == "A1"           # an alibi contradicts the line of inquiry directly
        if not addresses:
            s = round(s * 0.5, 3)                       # true, but it does not counter the evidence actually relied on
        alts.append({"code": code, "title": title, "statement": statement.format(n=name), "strength": s, "label": _label(s),
                     "evidence": items, "explainsSupporting": exp, "addressesSupportingEvidence": addresses, "test": test})
    alts.sort(key=lambda x: -x["strength"])
    S = a["confidence"]["supportWeight"]
    h_strength = round(1 - math.exp(-1.1 * S), 3)
    for i, x in enumerate(support):
        x["explainedBy"] = [al["code"] for al in alts if i in al["explainsSupporting"]]
    unexplained = [x for x in support if not x["explainedBy"]]
    top = alts[0] if alts else None
    if not alts:
        verdict = (f"No alternate explanation is supported by the records currently held. This does not confirm involvement — "
                   f"missing records ({', '.join(a['confidence']['sourcesMissing']).lower() or 'none'}) could hold one.")
        favour = "LINE_OF_INQUIRY_UNCONTESTED"
    elif top["code"] == "A1" and top["strength"] >= 0.6 and not any(s["source"] == "LOCATION" for s in support):
        verdict = (f"The alibi alternate (A1) is currently better supported than the line of inquiry: "
                   f"records place {name} elsewhere and none place them at the scene.")
        favour = "ALTERNATE"
    elif top["strength"] >= h_strength - 0.1:
        verdict = (f"Open: the line of inquiry ({h_strength:.2f}) and the strongest alternate — {top['code']} {top['title'].lower()} "
                   f"({top['strength']:.2f}) — are similarly supported. The tests below would separate them.")
        favour = "OPEN"
    elif unexplained:
        verdict = (f"The line of inquiry is better supported ({h_strength:.2f} vs {top['strength']:.2f} for {top['code']}): "
                   f"{len(unexplained)} supporting item(s) are not explained by any alternate.")
        favour = "LINE_OF_INQUIRY"
    else:
        verdict = (f"Every supporting item could be explained by at least one alternate, although the line of inquiry is "
                   f"stronger on weight ({h_strength:.2f} vs {top['strength']:.2f}). Test the alternates before relying on it.")
        favour = "OPEN"
    return {
        "framing": {"lineOfInquiry": f"{name} ({pid}) may have been involved in the incident recorded in {case_id}",
                    "alternate": f"{name} ({pid}) was not involved — the evidence has an innocent explanation",
                    "note": "KRONOS starts from the presumption of innocence. The line of inquiry and the alternates are tested "
                            "against the same records; neither is a finding, and the strengths are not probabilities."},
        "lineOfInquiryStrength": h_strength,
        "alternates": alts,
        "consideredNotSupported": considered,
        "comparison": {"favours": favour, "verdict": verdict, "strongestAlternate": top["code"] if top else None,
                       "unexplainedSupport": [x["text"] for x in unexplained],
                       "settleWith": [f"{al['code']} — {al['test']}" for al in alts[:3]]},
    }
